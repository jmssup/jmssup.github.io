import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createFilesystem, resolvePath, parseCommand, completeCommand, runCommand, routeForPath } from '../src/assets/terminal.js';

const posts = JSON.parse(await readFile('_site/search.json', 'utf8'));
const categories = JSON.parse(await readFile('src/_data/categories.json', 'utf8'));
const state = createFilesystem(posts, categories);
assert.equal(state.files.size, posts.length);
assert.equal(runCommand('ls', state).lines.length, 7);
assert.equal(state.directories.size, 6);
assert.deepEqual(routeForPath('/', state), { cwd: '/', command: 'ls' });
assert.deepEqual(routeForPath('/categories/ctf/', state), { cwd: '/ctf', command: 'ls' });
assert.deepEqual(routeForPath('/posts/tistory/147/', state), { cwd: '/development', command: 'open /development/tistory-147.md' });
assert.deepEqual(routeForPath('/about/', state), { cwd: '/', command: 'open /about.txt' });
assert.equal(routeForPath('/unknown/', state), null);
const korean = createFilesystem([{ ...posts[0], url: '/posts/소유권/' }], categories);
assert.equal(routeForPath('/posts/%EC%86%8C%EC%9C%A0%EA%B6%8C/', korean).command, 'open /development/소유권.md');
assert.deepEqual(parseCommand('grep "hello world" /development'), ['grep', 'hello world', '/development']);
assert.throws(() => parseCommand('grep "unclosed'), /따옴표/);
assert.equal(resolvePath('../../../../ctf', '/development'), '/ctf');
assert.equal(resolvePath('~/ctf'), '/ctf');
assert.equal(completeCommand('he', state).value, 'help ');
assert.equal(completeCommand('cd dev', state).value, 'cd development/');
assert.equal(completeCommand('cat /development/tistory-147', state).value, 'cat /development/tistory-147.md ');
runCommand('cd development', state);
assert.equal(runCommand('pwd', state).lines[0].text, '/development');
assert.equal(runCommand('ls', state).lines.length, posts.filter(post => post.categoryId === 'development').length);
assert.equal(runCommand('cat tistory-147.md', state).read.url, '/posts/tistory/147/');
assert.equal(runCommand('open tistory-147.md', state).location, '/posts/tistory/147/');
assert.equal(runCommand('open tistory-147.md', state).mode, 'rich');
assert.equal(runCommand('cat tistory-147.md', state).mode, 'text');
assert.equal(runCommand('about', state).read.url, '/about/');
assert.equal(runCommand('cat /about.txt', state).read.url, '/about/');
assert.match(runCommand('grep OP-TEE', state).lines[0].text, /^3개의/);
assert.equal(runCommand('grep OP-TEE tistory-147.md', state).lines.length, 2);
assert.match(runCommand('grep "no-such-query-9908"', state).lines[0].text, /^0개의/);
runCommand('cd -', state);
assert.equal(state.cwd, '/');
runCommand('cd research', state);
assert.match(runCommand('ls', state).lines[0].text, /아직 기록/);
assert.throws(() => runCommand('cd missing', state), /찾을 수 없습니다/);
assert.equal(state.cwd, '/research');
assert.throws(() => runCommand('cat /etc/passwd', state), /파일을 찾을 수 없습니다/);
assert.throws(() => runCommand('cat /development', state), /디렉터리입니다/);
assert.throws(() => runCommand('cat', state), /사용법/);
assert.throws(() => runCommand('<img src=x onerror=alert(1)>', state), /command not found/);
assert.equal(runCommand('clear', state).clear, true);
assert(runCommand('help', state).lines.some(line => line.command === 'ls development'));
assert.equal(runCommand('whoami', state).lines[0].text, 'guest');
state.history = ['ls', 'cd research', 'history'];
assert.match(runCommand('history', state).lines[0].text, /3  history/);
console.log(`PASS: terminal paths, commands, search, completion, invalid input and ${state.files.size} real post mappings.`);
