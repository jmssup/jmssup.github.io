import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createFilesystem, resolvePath, parseCommand, completeCommand, runCommand, routeForPath } from '../src/assets/terminal.js';

const posts = JSON.parse(await readFile('_site/search.json', 'utf8'));
const categories = JSON.parse(await readFile('src/_data/categories.json', 'utf8'));
const state = createFilesystem(posts, categories);
const topics = categories.filter(category => !category.id.includes('/'));
assert.equal(state.files.size, posts.length);
assert.equal(runCommand('ls', state).lines.length, topics.length + 1);
assert.equal(state.directories.size, categories.length);
assert.deepEqual(runCommand('ls', state).lines.slice(0,topics.length).map(line=>line.text), topics.map(c=>c.id + '/'));
assert.deepEqual(routeForPath('/', state), { cwd: '/', command: 'ls' });
assert.deepEqual(routeForPath('/categories/security/pwnable/', state), { cwd: '/security/pwnable', command: 'ls' });
assert.deepEqual(routeForPath('/posts/tistory/147/', state), { cwd: '/development/embedded', command: 'open /development/embedded/tistory-147.md' });
assert.deepEqual(routeForPath('/about/', state), { cwd: '/', command: 'open /about.txt' });
assert.equal(routeForPath('/unknown/', state), null);
for (const file of state.files.values()) {
  assert.deepEqual(routeForPath(file.url, state), { cwd: '/' + file.categoryId, command: `open ${file.path}` });
}
for (const category of categories) {
  const listing = runCommand('ls /' + category.id, state).lines;
  const children = categories.filter(c => c.id.startsWith(category.id + '/') && c.id.split('/').length === category.id.split('/').length + 1);
  assert.equal(listing.length, children.length + posts.filter(p=>p.categoryId===category.id).length);
  for (const child of children) {
    const row = listing.find(line=>line.command===`ls /${child.id}`);
    const count = posts.filter(p=>p.categoryId===child.id || p.categoryId.startsWith(child.id + '/')).length;
    assert.equal(row.detail, `${child.name} · ${count}개의 기록`);
  }
}
const korean = createFilesystem([{ ...posts[0], url: '/posts/소유권/' }], categories);
assert.equal(routeForPath('/posts/%EC%86%8C%EC%9C%A0%EA%B6%8C/', korean).command, 'open /development/embedded/소유권.md');
assert.deepEqual(parseCommand('grep "hello world" /development'), ['grep', 'hello world', '/development']);
assert.throws(() => parseCommand('grep "unclosed'), /따옴표/);
assert.equal(resolvePath('../../../../security', '/development/embedded'), '/security');
assert.equal(resolvePath('~/security/pwnable'), '/security/pwnable');
assert.equal(completeCommand('he', state).value, 'help ');
assert.equal(completeCommand('ho', state).value, 'home ');
assert.equal(completeCommand('tr', state).value, 'tree ');
assert.equal(completeCommand('cd dev', state).value, 'cd development/');
assert.equal(completeCommand('cd security/p', state).value, 'cd security/pwnable/');
assert.equal(completeCommand('cd development/e', state).value, 'cd development/embedded/');
assert.equal(completeCommand('cat /development/embedded/tistory-147', state).value, 'cat /development/embedded/tistory-147.md ');
assert(!completeCommand('cd security/',state).candidates.some(candidate=>candidate.includes('.md')));
assert.equal(runCommand('tree /', state).lines.length, categories.length + 1);
assert.equal(runCommand('tree /security', state).lines.length, categories.filter(c=>c.id.startsWith('security/')).length + 1);
assert.throws(() => runCommand('tree /missing',state), /사용법/);
runCommand('cd development/embedded', state);
assert.equal(runCommand('pwd', state).lines[0].text, '/development/embedded');
assert.equal(runCommand('cat tistory-147.md', state).read.url, '/posts/tistory/147/');
assert.equal(runCommand('open tistory-147.md', state).location, '/posts/tistory/147/');
assert.equal(runCommand('open tistory-147.md', state).mode, 'rich');
assert.equal(runCommand('cat tistory-147.md', state).mode, 'text');
assert.equal(runCommand('about', state).read.url, '/about/');
assert.equal(runCommand('cat /about.txt', state).read.url, '/about/');
assert.match(runCommand('grep OP-TEE /development', state).lines[0].text, /^3개의/);
assert.equal(runCommand('grep OP-TEE tistory-147.md', state).lines.length, 2);
assert.match(runCommand('grep "no-such-query-9908"', state).lines[0].text, /^0개의/);
runCommand('cd ..',state);
assert.equal(state.cwd,'/development');
assert.equal(completeCommand('cd e',state).value,'cd embedded/');
runCommand('cd -', state);
assert.equal(state.cwd, '/development/embedded');
const empty = createFilesystem([], categories);
runCommand('cd security/fuzzing', empty);
assert.match(runCommand('ls', empty).lines[0].text, /아직 기록/);
assert.throws(() => runCommand('cd missing', state), /찾을 수 없습니다/);
assert.equal(state.cwd, '/development/embedded');
assert.throws(() => runCommand('cat /etc/passwd', state), /파일을 찾을 수 없습니다/);
assert.throws(() => runCommand('cat /development', state), /디렉터리입니다/);
assert.throws(() => runCommand('cat', state), /사용법/);
assert.throws(() => runCommand('<img src=x onerror=alert(1)>', state), /command not found/);
assert.equal(runCommand('clear', state).clear, true);
assert(runCommand('help', state).lines.some(line => line.command === 'ls development'));
assert.equal(runCommand('whoami', state).lines[0].text, 'guest');
state.history = ['ls', 'cd development/embedded', 'history'];
assert.match(runCommand('history', state).lines[0].text, /3  history/);
assert.throws(() => runCommand('home extra', state), /사용법: home/);
const home = runCommand('home', state);
assert.equal(home.home, true);
assert.equal(home.location, '/');
assert.equal(state.cwd, '/');
assert.equal(state.previous, '/development/embedded');
assert.deepEqual(home.lines, runCommand('ls /', state).lines);
assert.deepEqual(state.history, ['ls', 'cd development/embedded', 'history']);
assert.match(runCommand('help', state).lines[1].text, /home\s+처음 화면/);
console.log(`PASS: nested terminal paths, tree, commands, subtree search, completion, invalid input and ${state.files.size} real post mappings.`);
